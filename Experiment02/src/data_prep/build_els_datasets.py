"""
Build UniGAD's expected `datasets/edge_labels/<name>-els` files from GADBench's raw
node-labeled graphs (Tang et al., "GADBench", NeurIPS 2024 -- cited as [49] in the UniGAD
paper and as "Node and Edge level Baselines" in this repo's README.MD).

UniGAD's own repo ships no dataset-construction code and no Amazon/YelpChi/T-Finance files
(only weibo-els is committed). The UniGAD paper (arXiv:2411.06427, Section 4.1, p.7) states
edge labels are not a separate release but were generated by the authors themselves:

    "For edge labels, we generated them according to a specific anomaly probability
    following the formula P_anom^(i,j) = avg(P_i_anom, P_j_anom)."

This script reproduces that: it loads a GADBench raw graph (features + node labels only),
renames the node-label field to what UniGAD's loader expects (`node_label`), derives
`edge_label` from the averaging formula above, and saves the result in the exact format
`Dataset.__init__`'s edge_labels branch reads (src/utils.py:409-437): a single-graph DGL
`.bin` file with `ndata['feature']`, `ndata['node_label']`, `edata['edge_label']`.

The paper does not spell out the exact binarization threshold for the averaged probability,
so this script computes BOTH candidate rules (any-endpoint-anomalous, both-endpoints-
anomalous) and prints the resulting edge-anomaly rate for comparison against the paper's
own Table 1 statistics before saving -- only the rule you pick with --edge_rule is written
to disk. Does not modify any file under src/ outside this new data_prep/ subpackage.
"""
import argparse
import os

import dgl
import torch
from dgl.data.utils import load_graphs, save_graphs

# Paper's Table 1 edge-anomaly percentages, for sanity-checking the reconstruction.
PAPER_EDGE_AB_PCT = {
    "reddit": 2.72,
    "weibo": 5.71,
    "amazon": 2.49,
    "yelp": 13.89,
    "tolokers": 33.44,
    "questions": 7.50,
    "tfinance": 2.77,
}

FEATURE_KEY_CANDIDATES = ["feature", "feat", "x"]
LABEL_KEY_CANDIDATES = ["label", "node_label", "y"]


def _pick_key(ndata, candidates, what):
    for k in candidates:
        if k in ndata:
            return k
    raise KeyError(
        f"Could not find a {what} field among {candidates} in ndata; "
        f"available keys: {list(ndata.keys())}"
    )


def build_one(name, gadbench_dir, out_dir, edge_rule):
    src_path = os.path.join(gadbench_dir, name)
    graph = load_graphs(src_path)[0][0]

    feat_key = _pick_key(graph.ndata, FEATURE_KEY_CANDIDATES, "feature")
    label_key = _pick_key(graph.ndata, LABEL_KEY_CANDIDATES, "label")

    feature = graph.ndata[feat_key].float()
    node_label = graph.ndata[label_key].long().reshape(-1)

    src, dst = graph.edges()
    p_avg = (node_label[src].float() + node_label[dst].float()) / 2.0

    edge_label_any = (p_avg >= 0.5).long()   # >=0.5: at least one endpoint anomalous
    edge_label_both = (p_avg > 0.5).long()   # >0.5: both endpoints anomalous

    n_edges = p_avg.numel()
    pct_any = 100.0 * edge_label_any.sum().item() / n_edges
    pct_both = 100.0 * edge_label_both.sum().item() / n_edges
    target = PAPER_EDGE_AB_PCT.get(name)

    print(f"[{name}] nodes={graph.num_nodes()} edges={n_edges} "
          f"node_ab%={100.0 * node_label.float().mean().item():.2f} "
          f"edge_ab%(any)={pct_any:.2f} edge_ab%(both)={pct_both:.2f} "
          f"paper_target%={target}")

    edge_label = edge_label_any if edge_rule == "any" else edge_label_both

    out_graph = dgl.graph((src, dst), num_nodes=graph.num_nodes())
    out_graph.ndata["feature"] = feature
    out_graph.ndata["node_label"] = node_label
    out_graph.edata["edge_label"] = edge_label

    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, f"{name}-els")
    save_graphs(out_path, [out_graph])
    print(f"[{name}] saved -> {out_path}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gadbench_dir", type=str, required=True,
                         help="Directory containing GADBench's extracted raw graph files "
                              "(e.g. .../datasets/reddit, .../datasets/amazon, ...)")
    parser.add_argument("--out_dir", type=str, default="../datasets/edge_labels")
    parser.add_argument("--datasets", type=str,
                         default="reddit,weibo,amazon,yelp,tolokers,questions,tfinance")
    parser.add_argument("--edge_rule", type=str, choices=["any", "both"], default="any")
    args = parser.parse_args()

    for name in args.datasets.split(","):
        build_one(name, args.gadbench_dir, args.out_dir, args.edge_rule)


if __name__ == "__main__":
    main()
